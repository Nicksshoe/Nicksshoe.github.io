# Regenerates itemgroups.js: which items can't be owned together (Last Whisper, Spellblade, Hydra, Lifeline,
# Boots, ...), read from Riot's game files via CommunityDragon. Run after each patch, then rebuild the Worker.
param([string]$Patch)
$root = Split-Path $PSScriptRoot -Parent
if (-not $Patch) { $Patch = (Invoke-RestMethod 'https://ddragon.leagueoflegends.com/api/versions.json')[0] }
$dd = Invoke-RestMethod "https://ddragon.leagueoflegends.com/cdn/$Patch/data/en_US/item.json"
$bin = (Invoke-WebRequest 'https://raw.communitydragon.org/latest/game/items.cdtb.bin.json' -UseBasicParsing).Content | ConvertFrom-Json -AsHashtable

$out = [ordered]@{}
foreach ($p in $dd.data.PSObject.Properties) {
  $id = $p.Name; if ([int]$id -ge 10000 -or -not $p.Value.maps.'11') { continue }
  $it = $bin["Items/$id"]; if (-not $it) { continue }
  $groups = @()
  foreach ($g in $it.mItemGroups) {
    if ($g -eq 'Items/ItemGroups/Default') { continue }
    $go = $bin[$g]; if (-not $go) { continue }
    $max = $go.mMaxGroupOwnable
    if ($null -eq $max -or $max -lt 1 -or $max -gt 5) { continue }
    $name = if ($g -like 'Items/ItemGroups/*') { $g.Substring(17) } else { $g }
    $groups += , @($name, [int]$max)
  }
  if ($groups.Count) { $out[$id] = $groups }
}
$json = $out | ConvertTo-Json -Depth 5 -Compress
$js = "/* GENERATED by tools/update-itemgroups.ps1 from Riot's game files (patch $Patch) - do not edit.`n" +
      "   Item id -> [[group, max owned], ...]: e.g. only one Last Whisper item, one Spellblade item, one pair of boots. */`n" +
      "(function (root) { root.Potenshall = root.Potenshall || {}; root.Potenshall.ItemGroups = $json; })(typeof window !== 'undefined' ? window : globalThis);`n"
Set-Content -Path (Join-Path $root 'itemgroups.js') -Value $js -Encoding utf8
Write-Host "Wrote itemgroups.js ($($out.Count) items with limits, patch $Patch)"
