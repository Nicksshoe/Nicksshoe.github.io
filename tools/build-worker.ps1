# Bundles the game engine + leaderboard handler into one Worker script: worker/dist/worker.js
# Rebuild and redeploy after changing engine.js, abilities.js or passives.js, so server scores match the game.
$root = Split-Path $PSScriptRoot -Parent
$out = Join-Path $root 'worker/dist/worker.js'
New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
$parts = @('engine.js', 'abilities.js', 'passives.js', 'itemgroups.js', 'cc.js', 'growth.js', 'worker/handler.js') | ForEach-Object { Get-Content (Join-Path $root $_) -Raw }
$header = "// GENERATED by tools/build-worker.ps1 - do not edit. Source: engine.js, abilities.js, passives.js, itemgroups.js, cc.js, growth.js, worker/handler.js`n"
# Fingerprint of the sources (line endings ignored), served at the Worker's / so you can see which build is live.
$sha = [Security.Cryptography.SHA256]::Create()
$build = ([BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes((($parts -join "`n") -replace "`r", '')))) -replace '-', '').Substring(0, 12).ToLower()
$header += "const BUILD = '$build';`n"
Set-Content -Path $out -Value ($header + ($parts -join "`n;`n")) -Encoding utf8
Write-Host "Built $out ($([Math]::Round((Get-Item $out).Length / 1KB)) KB), build $build"
Write-Host "After deploying, https://potenshall-leaderboard.jacob-bc1.workers.dev/ should show build $build"
# The pages load the same files: refresh their fingerprints so browsers fetch the new versions right away.
& (Join-Path $PSScriptRoot 'stamp-assets.ps1')
