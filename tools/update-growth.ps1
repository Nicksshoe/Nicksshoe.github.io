# Regenerates growth.js: each champion's attack damage per level, read from the game files (CommunityDragon).
# Data Dragon reports attackdamageperlevel = 0 for every champion since patch 16.1, but the game still has it,
# so the engine uses this table instead. Run after each patch, then rebuild the Worker.
param([string]$Patch)
$root = Split-Path $PSScriptRoot -Parent
if (-not $Patch) { $Patch = (Invoke-RestMethod 'https://ddragon.leagueoflegends.com/api/versions.json')[0] }
$ids = (Invoke-RestMethod "https://ddragon.leagueoflegends.com/cdn/$Patch/data/en_US/champion.json").data.PSObject.Properties.Name
$results = $ids | ForEach-Object -ThrottleLimit 12 -Parallel {
  $id = $_; $lc = $id.ToLower()
  try {
    $raw = (Invoke-WebRequest "https://raw.communitydragon.org/latest/game/data/characters/$lc/$lc.bin.json" -UseBasicParsing).Content
    # The champion's own record ("Characters/<Name>/CharacterRecords/Root"), then its damagePerLevel value.
    $i = $raw.IndexOf('/CharacterRecords/Root":{')
    $m = [regex]::Match($raw.Substring([Math]::Max(0, $i)), '"damagePerLevelModifiable":\{"baseValue":([0-9.eE+-]+)')
    if ($i -ge 0 -and $m.Success) { [pscustomobject]@{ id = $id; v = [Math]::Round([double]$m.Groups[1].Value, 3) } }
    else { [pscustomobject]@{ id = $id; v = $null } }
  } catch { [pscustomobject]@{ id = $id; v = $null } }
}
$missing = @($results | Where-Object { $null -eq $_.v } | ForEach-Object id)
$out = [ordered]@{}
foreach ($r in ($results | Where-Object { $null -ne $_.v } | Sort-Object id)) { $out[$r.id] = $r.v }
$json = $out | ConvertTo-Json -Compress
$js = "/* GENERATED by tools/update-growth.ps1 from the game files via CommunityDragon (patch $Patch) - do not edit.`n" +
      "   Champion id -> attack damage gained per level (Data Dragon reports 0 for all champions since 16.1). */`n" +
      "(function (root) { root.Potenshall = root.Potenshall || {}; root.Potenshall.AdGrowth = $json; })(typeof window !== 'undefined' ? window : globalThis);`n"
Set-Content -Path (Join-Path $root 'growth.js') -Value $js -Encoding utf8
Write-Host "Wrote growth.js ($($out.Count) champions, patch $Patch)"
if ($missing.Count) { Write-Host "Missing (left at Data Dragon value): $($missing -join ', ')" }
